/// <summary>
/// Один шаг пайплайна таргетинга.
/// Шаги последовательно применяются к <see cref="TargetingContext"/>:
///   • пул     — добавляет новых кандидатов,
///   • фильтр  — удаляет неподходящих кандидатов,
///   • сортер  — упорядочивает или обрезает список,
///   • условие выхода — проверяет и при необходимости прерывает пайплайн.
///
/// Пайплайн можно произвольно комбинировать: Пул → Фильтр → Сортер → Условие → Пул → …
/// </summary>
public interface ITargetingStep
{
    /// <summary>Выполняет шаг, изменяя <see cref="TargetingContext.Candidates"/> и/или управляющие флаги.</summary>
    void Execute(TargetingContext context);
}
